"""The tested install, written down and hash-pinned: lock/requirements.txt.

requirements.txt pins the 17 packages Curatarr imports; everything they
pull in (~90 packages) was unpinned and invisible until 2026-09-22, when
the first real OSV scan showed the install running anyio 4.13.0 inside two
advisories. The lock is a *universal* pip requirements file — every package
of the closure with its version, an environment marker where a package is
platform-specific (uvloop on Linux, pywin32 on Windows) and the sha256 of
every distribution file — generated by ``uv pip compile --universal
--generate-hashes`` from requirements.txt (``--compile``). CI installs from
it with ``--require-hashes``; the launchers raise a package that fell below
it through the same hash check; scanners and Dependabot read it.

Rules, so the file can never lie or bite:

* The lock is the source of truth for versions. requirements.txt repeats
  the lock's versions for the direct pins (``--apply`` and ``--sync-pins``
  copy them over; requirements.txt never runs ahead of the lock — bump the
  lock with ``--compile`` for a deliberate change).
* The lock never lowers anything. A package installed below its lock line
  is raised (``pip install --require-hashes --no-deps`` from a temporary
  file holding exactly those lines); a package installed above it raises
  the lock line instead, with the hashes fetched from PyPI (offline: the
  line stays and the report says so).
* Entries whose marker rules them out on this platform are neither
  installed nor removed.
* A plain ``name==version`` line (no hashes) still works — that is what the
  lock looked like before uv — the raise then runs without the hash check.

    python -m src.deps_lock              report; exit 1 when anything differs
    python -m src.deps_lock --apply      raise below, follow above, sync the pins into requirements.txt
    python -m src.deps_lock --sync-pins  only the requirements.txt step
    python -m src.deps_lock --compile    regenerate every lock/*.txt from its input with uv

Marker evaluation and version ordering come from `packaging`, which is part
of the closure itself; when even that is missing (a venv before its first
pip run) the launchers skip the lock step and say so.
"""
